def main(path):
    with io.open(path, "r", encoding="utf-8") as f:
        doc = json.load(f)

    chars = doc["Characters"]
    by_id = {c["CharacterId"]: c for c in chars}
    missing = [cid for cid in DATA if cid not in by_id]
    if missing:
        print("未找到角色:", missing)
        sys.exit(1)

    for cid, upd in DATA.items():
        c = by_id[cid]
        if "displayName" in upd:
            c["DisplayName"] = upd["displayName"]
        if "title" in upd:
            c["Title"] = upd["title"]
        if "lore" in upd:
            c["Lore"] = upd["lore"]
        if "story" in upd:
            c["Story"] = upd["story"]
        if "faction" in upd:
            c["Faction"] = upd["faction"]
        if "voices" in upd:
            c["Voices"] = upd["voices"]
        if "weapon" in upd:
            c["Weapon"] = upd["weapon"]
        if "weaponDesc" in upd:
            c["WeaponDesc"] = upd["weaponDesc"]
        if "skills" in upd:
            for s in c["Skills"]:
                if s["SkillId"] in upd["skills"]:
                    name, desc = upd["skills"][s["SkillId"]]
                    s["DisplayName"] = name
                    s["Description"] = desc

    with io.open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("已更新角色数:", len(DATA))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data.json")
